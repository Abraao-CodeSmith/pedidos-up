import axios from 'axios';

const API_BASE_URL = import.meta.env.VITE_API_URL || '/api';

const api = axios.create({
  baseURL: API_BASE_URL,
  headers: {
    'Content-Type': 'application/json'
  }
});

// Interceptor para injetar o Token JWT em requisições autenticadas
api.interceptors.request.use(
  (config) => {
    const token = localStorage.getItem('pedidosup_token');
    if (token) {
      config.headers.Authorization = `Bearer ${token}`;
    }
    return config;
  },
  (error) => Promise.reject(error)
);

// Interceptor para tratar erros de autenticação (401)
api.interceptors.response.use(
  (response) => response,
  (error) => {
    if (error.response && error.response.status === 401) {
      localStorage.removeItem('pedidosup_token');
      localStorage.removeItem('pedidosup_user');
      // Redireciona para /login se não estiver já na página pública de rastreamento ou auth
      if (!window.location.pathname.startsWith('/track') && !window.location.pathname.startsWith('/login')) {
        window.location.href = '/login';
      }
    }
    return Promise.reject(error);
  }
);

export default api;
